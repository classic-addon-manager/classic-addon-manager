/// Tailwind palette colour, e.g. `tw(Tw::Emerald, 500)`. `shade` is one of 50,100,...,900,950.
pub fn tw(family: Tw, shade: u16) -> Hsla {
    let ix = match shade {
        50 => 0,
        100 => 1,
        200 => 2,
        300 => 3,
        400 => 4,
        500 => 5,
        600 => 6,
        700 => 7,
        800 => 8,
        900 => 9,
        950 => 10,
        _ => panic!("invalid tailwind shade {shade}"),
    };
    let (l, c, h) = TABLE[family as usize][ix];
    oklch(l, c, h)
}
