#!/usr/bin/env python3
"""Copy lucide icons into crates/cam_ui/assets/icons/<name>.svg and regenerate crates/cam_ui/src/icons_generated.rs.

Usage: tools/gen_icons.py NAME [NAME ...]
  NAME      kebab-case lucide name (circle-check) or PascalCase export (CircleCheck), aliases work too.
  DEST=SRC  write lucide icon SRC as assets/icons/DEST.svg, for icon names gpui-component expects:
            close=x dash=minus inspector=bug sort-ascending=arrow-up-narrow-wide
            sort-descending=arrow-down-wide-narrow window-close=x window-maximize=square
            window-minimize=minus window-restore=copy resize-corner=grip

Icons come from the latest lucide-static npm package. It is downloaded and unpacked into a temporary
directory that is deleted afterwards. Existing files with the same name are overwritten."""
import json, os, subprocess, sys, tarfile, tempfile
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
OUT = os.path.join(ROOT, "crates/cam_ui/assets/icons")
REGISTRY = "https://registry.npmjs.org/lucide-static/latest"
ICON_DIR = "package/icons/"

def pascal(kebab):
    return "".join(p[:1].upper() + p[1:] for p in kebab.split("-"))

def parse_args(args):
    """-> [(dest, requested source name)]"""
    if not args:
        raise SystemExit(__doc__)
    pairs = []
    for a in args:
        dest, _, src = a.partition("=")
        pairs.append((dest, src or dest))
    return pairs

def convert(svg_text):
    """lucide-static SVG -> the single-line form used in assets/icons."""
    root = ET.fromstring(svg_text)
    body = ""
    for el in root:
        if len(el):
            raise SystemExit("nested SVG elements are not supported")
        tag = el.tag.split("}")[-1]
        attrs = " ".join(f'{k}="{escape(v, {chr(34): "&quot;"})}"' for k, v in el.attrib.items())
        body += f"<{tag} {attrs}/>"
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" '
            'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">' + body + "</svg>\n")

def fetch(pairs, tmp):
    """Download lucide-static into tmp, extract the requested icons there, -> {dest: svg text}."""
    # curl instead of urllib: it uses the OS certificate store, which some Python builds (msys2) lack.
    meta = json.loads(subprocess.run(["curl", "-fsSL", REGISTRY], check=True, capture_output=True).stdout)
    print(f"lucide-static {meta['version']}")
    tgz = os.path.join(tmp, "lucide-static.tgz")
    subprocess.run(["curl", "-fsSL", "-o", tgz, meta["dist"]["tarball"]], check=True)
    with tarfile.open(tgz) as tf:
        members = {m.name[len(ICON_DIR):-4]: m for m in tf.getmembers()
                   if m.isfile() and m.name.startswith(ICON_DIR) and m.name.endswith(".svg")}
        by_pascal = {pascal(n): n for n in members}
        resolved = {}
        unknown = []
        for dest, src in pairs:
            name = src if src in members else by_pascal.get(src)
            if name is None:
                unknown.append(src)
            else:
                # PascalCase requests without an explicit DEST are written under the kebab name
                resolved[name if dest == src else dest] = name
        if unknown:
            raise SystemExit("unknown icon(s): " + " ".join(unknown))
        icons_tmp = os.path.join(tmp, "icons")
        os.makedirs(icons_tmp)
        out = {}
        for dest, name in resolved.items():
            path = os.path.join(icons_tmp, name + ".svg")
            if not os.path.exists(path):
                with tf.extractfile(members[name]) as src_f, open(path, "wb") as dst_f:
                    dst_f.write(src_f.read())
            with open(path, encoding="utf-8") as f:
                out[dest] = f.read()
        return out

def write_constants():
    allf = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith(".svg"))
    lines = ["// @generated by tools/gen_icons.py -- do not edit. One `Lucide` const per assets/icons/*.svg.",
             "use super::icons::Lucide;", ""]
    for f in allf:
        ident = f.upper().replace("-", "_")
        if ident[0].isdigit(): ident = "_" + ident
        lines.append(f'pub const {ident}: Lucide = Lucide("{f}");')
    with open(os.path.join(ROOT, "crates/cam_ui/src/icons_generated.rs"), "w") as f:
        f.write("\n".join(lines) + "\n")
    return len(allf)

# Custom title-bar glyphs, 16x16 viewBox, drawn with stroke=currentColor
def win(body):
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16" fill="none" '
            'stroke="currentColor">' + body + '</svg>\n')
CUSTOM = {
    "win-minimize": win('<path d="M3 8.5H13" stroke-width="1.5" stroke-linecap="round"/>'),
    "win-maximize": win('<rect x="3.75" y="3.75" width="8.5" height="8.5" rx="0.5" stroke-width="1.3"/>'),
    "win-restore": win('<path d="M5 3.75H12.25V11" stroke-width="1.3" stroke-linecap="round" stroke-linejoin="round"/>'
                       '<path d="M10.75 6H3.75V13H10.75V6Z" stroke-width="1.3" stroke-linejoin="round"/>'),
    "win-close": win('<path d="M4 4L12 12" stroke-width="1.5" stroke-linecap="round"/>'
                     '<path d="M12 4L4 12" stroke-width="1.5" stroke-linecap="round"/>'),
}
# NOTE: assets/icons/discord.svg is not a Lucide icon. It was extracted by hand and is kept as is.

def main():
    pairs = parse_args(sys.argv[1:])
    with tempfile.TemporaryDirectory(prefix="gen_icons_") as tmp:
        icons = fetch(pairs, tmp)
    os.makedirs(OUT, exist_ok=True)
    files = {dest: convert(svg) for dest, svg in icons.items()}
    files.update(CUSTOM)
    for name, svg in files.items():
        with open(os.path.join(OUT, name + ".svg"), "w") as f:
            f.write(svg)
    print("wrote", " ".join(sorted(icons)))
    print(write_constants(), "icons")

if __name__ == "__main__":
    main()
